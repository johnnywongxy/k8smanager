"""把 kubeasz 的 bin 目录加进节点的**系统** PATH。

kubeasz 把 kubelet、kubectl、crictl、etcdctl、calicoctl 这些命令拷到 inventory 里的
``bin_dir``（默认 ``/opt/kube/bin``，见 ``compiler.bin_dir``），然后只做了一件事：
在**连接用户的 ``~/.bashrc`` 末尾追加一行**

.. code-block:: sh

    export PATH=/opt/kube/bin:$PATH  # generated by kubeasz:custom PATH

（``roles/prepare/tasks/main.yml``）。这一个动作留下三个洞：

1. 只有那一个用户、只有交互式 shell 有 —— ``su`` 成别的用户、``ssh 节点 'kubectl ...'``、
   cron、以及 ansible 的 ``command: kubectl`` 全都看不到，报的是 ``command not found``。
   运维在节点上排查故障时最常用的恰好就是 ``ssh 节点 'kubectl get pod -A'`` 这种一次性命令。
2. ``.bashrc`` 会被操作员按自己的习惯重写，那一行跟着一起消失，而且没有任何迹象。
3. 卸载集群时 kubeasz 会把那一行删掉，但 ``bin_dir`` 本身留着，命令还在机器上却找不到。

于是在节点上补两处系统级配置：

- ``/etc/profile.d/kubeasz-path.sh``：所有用户、所有登录 shell 都生效，内容自解释，
  删文件即撤销。
- ``/etc/environment`` 里的 ``PATH=``：这是非交互式 SSH 会话真正的 PATH 来源 ——
  ``sshd`` 的 PAM 栈里 ``pam_env`` 读它，而它**不读** ``/etc/profile.d/``。
  这是 ``ssh 节点 'kubectl ...'`` 能跑起来的关键，也是唯一一处需要改既有文件的地方，
  所以按「读出原文 → 改 PATH 那一行 → 原子替换 → 回读核对」来做，任何一步不合预期就跳过
  并写日志，绝不覆盖认不出来的内容。

**两处都是尽力而为，不作为部署成败的判据。** 这纯粹是给人用的便利配置：写不进去时集群本身
照样是好的，为它判失败会把一次成功的部署报成失败。因此 ``apply_node`` 只在**两处都没写成**
时抛错，调用方逐台 try/except 记日志（与节点侧镜像仓库的卸载同一种口吻）。

**撤销**：``remove_node`` 对称地删掉那个文件、并从 ``PATH=`` 里摘掉 ``bin_dir``，
两者都靠文件开头的标记确认是自己写的 —— ``bin_dir`` 里的命令本身归 kubeasz 管，销毁集群时
它不删这些命令（``roles/clean`` 里那一步是注释掉的），平台也不越权删。
"""

import base64

from . import compiler, node_registry

# 系统级 PATH 的两处落点。
PROFILE_DIR = '/etc/profile.d'
PROFILE_PATH = f'{PROFILE_DIR}/kubeasz-path.sh'
ENVIRONMENT_PATH = '/etc/environment'
# /etc/environment 里要改的那一行。键名大小写敏感，pam_env 不认小写的 path。
ENVIRONMENT_KEY = 'PATH'

# 文件首行标记，用来确认这个文件是平台写的。撤销与重写都先看它一眼：
# 操作员手工改过就拿回来（撤销时不动它），重写时也只覆盖自己那份。
PROFILE_MARKER = '# generated by k8smanager: 让所有用户与非交互式 shell 都能直接用 kubeasz 的命令'
PROFILE_HINT = '# 撤销：删掉本文件即可（kubeasz 自己在连接用户 ~/.bashrc 里加的那一行不受影响）'

# 写临时文件再改名，保证 /etc/environment 不会读到写了一半的内容。
TEMP_SUFFIX = '.k8smanager.tmp'


class NodePathError(Exception):
    """节点上的 PATH 配置写不进去，携带可直接展示给用户的中文原因与错误码。

    参数：`error_code` 表示机器可读的错误码；`message` 表示中文原因。
    返回：无显式返回值。
    副作用：只承载信息，不执行动作。

    与 ``NodeRegistryError`` 同理，本模块不直接抛 ``state_machine.TaskAborted``：
    那个类在导入方向上属于上层，由调用方转换。
    """

    def __init__(self, error_code, message):
        super().__init__(message)
        self.error_code = error_code
        self.message = message


# ---- 纯计算：文件内容与命令文本 ----------------------------------------


def profile_content(bin_dir):
    """生成 ``/etc/profile.d/kubeasz-path.sh`` 的内容。

    参数：`bin_dir` 表示节点上的 kubeasz 二进制目录。
    返回：返回文件文本。
    副作用：只做纯计算。

    写成「赋值」而不是「追加」：这个文件归平台独占，重写比追加简单，也天然幂等 ——
    重复执行、改过 ``bin_dir`` 之后再执行，结果都对。
    """
    return f'{PROFILE_MARKER}\n{PROFILE_HINT}\nexport PATH={bin_dir}:$PATH\n'


def environment_content(text, bin_dir, add=True):
    """在 ``/etc/environment`` 的正文里加上或摘掉 ``bin_dir``。

    参数：`text` 表示文件原文；`bin_dir` 表示要处理的目录；`add` 为真表示加入，为假表示摘除。
    返回：返回 ``(新正文, {matched, changed, before, after})``。
    副作用：只做纯计算，不接触文件系统。

    ``pam_env`` 的语法是 ``键=值``，值可以用引号包起来，**不做变量展开** —— 所以这里既不能
    写 ``$PATH``，也不能把 ``bin_dir`` 追加到行尾了事：必须读出原来那一串，在冒号分隔的
    列表里增删。引号风格按原样保留，免得把操作员写的引号吃掉。

    只认顶格的 ``PATH=``：有缩进的行不是合法赋值。注释行（``#`` 开头）不动 ——
    操作员常常把用过的配置注释掉留着，改它等于覆盖人家的工作笔记。
    """
    lines = text.splitlines()
    trailing_newline = text.endswith('\n')
    output = []
    matched = 0
    changed = False
    before = ''
    after = ''

    for line in lines:
        parts = _path_parts(line)
        if parts is None:
            output.append(line)
            continue
        quote, inner, entries = parts
        if matched == 0:
            before = inner
        matched += 1

        if add:
            if bin_dir in entries:
                if matched == 1:
                    after = inner
                output.append(line)
                continue
            new_inner = f'{bin_dir}:{inner}' if inner else bin_dir
        else:
            if bin_dir not in entries:
                if matched == 1:
                    after = inner
                output.append(line)
                continue
            new_inner = ':'.join(item for item in entries if item != bin_dir)
            if not new_inner:
                # 摘完就空了：与其留下 ``PATH=``（登录后什么命令都找不到），不如整行去掉，
                # 让 PATH 退回系统默认值。
                changed = True
                if matched == 1:
                    after = ''
                continue

        changed = True
        if matched == 1:
            after = new_inner
        output.append(f'{ENVIRONMENT_KEY}={quote}{new_inner}{quote}')

    result = '\n'.join(output)
    if trailing_newline and output:
        result += '\n'
    return result, {'matched': matched, 'changed': changed, 'before': before, 'after': after}


def _path_parts(line):
    """把一行解析成 ``(引号, 值, 冒号分隔的条目)``，不是顶格的 ``PATH=`` 就返回 None。

    参数：`line` 表示文件里的一行。
    返回：返回三元组；该行不是 PATH 赋值时返回 None。
    副作用：只做纯计算。
    """
    if not line or line[0] in ' \t#' or '=' not in line:
        return None
    key, _, raw = line.partition('=')
    if key.strip() != ENVIRONMENT_KEY or key != key.strip():
        return None
    value = raw.strip()
    quote = ''
    if len(value) >= 2 and value[0] == value[-1] and value[0] in ('"', "'"):
        quote = value[0]
        value = value[1:-1]
    return quote, value, value.split(':') if value else []


def write_text_command(path, text, mode='644'):
    """生成「把一段文本写到节点某个文件」的命令。

    参数：`path` 表示目标路径；`text` 表示文件内容；`mode` 表示落地权限。
    返回：返回一段 shell 命令。
    副作用：只做纯计算。

    走 base64 而不是 SFTP，也不走 heredoc：``/etc/environment`` 这类文件里可能有引号、
    反斜杠、通配符，经 shell 引号规则搬运迟早会咬到某一行；base64 只含
    ``[A-Za-z0-9+/=]``，塞进单引号里绝对安全。这也让本步骤不依赖节点的 SFTP 子系统
    （硬化的机器上常被关掉），只有 SSH 通道就够。

    先写同目录的临时文件再 ``mv`` 覆盖：``mv`` 是原子改名，读 ``/etc/environment`` 的
    ``pam_env`` 永远看不到写了一半的内容。命令末尾 ``cat`` 回显落地结果，调用方据此核对。
    """
    payload = base64.b64encode(str(text).encode('utf-8')).decode('ascii')
    temporary = f'{path}{TEMP_SUFFIX}'
    return (
        f"printf '%s' '{payload}' | base64 -d > {temporary} && "
        f'chmod {mode} {temporary} && '
        f'mv -f {temporary} {path} && '
        f'cat {path}'
    )


def read_text_command(path):
    """生成「把节点上的文件原样读回来」的命令。

    参数：`path` 表示文件路径。
    返回：返回一段 shell 命令。
    副作用：只做纯计算。

    输出经 base64 走一遍，是因为 ``credentials.run_command`` 会 ``strip()`` 掉标准输出首尾
    空白 —— 直接 ``cat`` 会把文件结尾的换行、开头的空行一起吃掉，回写时那几行就莫名其妙
    消失了。base64 是单行的，strip 掉换行正好，解码回来逐字节还原。
    """
    return f"base64 {path} | tr -d '\\n'"


def read_text(client, path):
    """读回节点上一个文件的原文。

    参数：`client` 表示已连接的客户端；`path` 表示文件路径。
    返回：返回 ``(退出码, 文本, 错误说明)``；文件不存在或读不到时退出码非零、文本为空。
    副作用：在目标机上执行一条只读命令。
    """
    code, out, err = node_registry.run(client, read_text_command(path))
    if code != 0:
        return code, '', err or f'读取 {path} 失败'
    try:
        return 0, base64.b64decode(out.encode('ascii')).decode('utf-8'), ''
    except (ValueError, UnicodeDecodeError) as exc:
        return 1, '', f'{path} 读回来的内容不是可解析的文本（{exc}）'


def profile_command(bin_dir):
    """生成写入 ``/etc/profile.d/kubeasz-path.sh`` 的命令。

    参数：`bin_dir` 表示节点上的 kubeasz 二进制目录。
    返回：返回一段 shell 命令。
    副作用：只做纯计算。
    """
    return write_text_command(PROFILE_PATH, profile_content(bin_dir))


def profile_remove_command():
    """生成撤销 ``/etc/profile.d/kubeasz-path.sh`` 的命令。

    参数：无。
    返回：返回一段 shell 命令。
    副作用：只做纯计算。

    只删自己写的那个文件：内容不以标记开头时原样留着并回显 ``KEPT``。文件里没有别的东西，
    误删的风险本就不大，但一条 ``grep`` 就能确认的事没必要省。
    """
    return (
        f'if [ -f {PROFILE_PATH} ]; then '
        f'if head -n 1 {PROFILE_PATH} | grep -qF {_single_quote(PROFILE_MARKER)}; then '
        f'rm -f {PROFILE_PATH} && echo REMOVED; '
        f'else echo KEPT; fi; '
        'else echo ABSENT; fi'
    )


def _single_quote(text):
    """把一段文本包成 shell 单引号字面量。

    参数：`text` 表示要包裹的文本。
    返回：返回可直接放进命令的引号文本。
    副作用：只做纯计算。
    """
    return "'" + str(text).replace("'", "'\\''") + "'"


# ---- 节点侧执行 --------------------------------------------------------


def apply_node(context, node, bin_dir_value, credential=None, key_path=None, client_factory=None):
    """把 ``bin_dir`` 加进一台节点的系统 PATH。

    参数：`context` 表示任务上下文；`node` 表示节点快照；`bin_dir_value` 表示节点上的
        kubeasz 二进制目录；`credential` 表示连接信息；`key_path` 表示部署私钥路径；
        `client_factory` 表示可注入的连接工厂，便于测试。
    返回：返回 ``{'label', 'profile', 'environment'}`` 的报告字典，任一项失败时该项为错误说明。
    副作用：修改目标机的 ``/etc/profile.d/kubeasz-path.sh`` 与 ``/etc/environment``。

    幂等：两处都按内容判断，重复执行不会重复追加。
    两处都失败才抛 ``NodePathError``；只成一处的照样返回报告，由调用方写进日志提醒操作员。
    """
    label = str(getattr(node, 'ip_address', '') or '') or getattr(node, 'name', '节点')
    client = node_registry.open_session(
        node, credential, key_path=key_path, client_factory=client_factory,
    )
    try:
        report = {'label': label}
        report['profile'] = _write_profile(context, client, label, bin_dir_value)
        report['environment'] = _ensure_environment(context, client, label, bin_dir_value)
    finally:
        node_registry.close_session(client)

    if report['profile'] is not True and report['environment'] is not True:
        raise NodePathError(
            'node_path_failed',
            f'节点 {label} 上两处 PATH 配置都没写成（{PROFILE_PATH}：{report["profile"]}；'
            f'{ENVIRONMENT_PATH}：{report["environment"]}）。',
        )
    return report


def _write_profile(context, client, label, bin_dir_value):
    """写 ``/etc/profile.d/kubeasz-path.sh``，成功返回 True，失败返回中文原因。

    参数：`context` 表示任务上下文；`client` 表示已连接的客户端；`label` 表示节点标识；
        `bin_dir_value` 表示二进制目录。
    返回：成功返回 True；失败返回原因文本。
    副作用：在目标机上创建或覆盖一个文件。

    失败只返回原因、不抛异常：这个文件和 ``/etc/environment`` 是两条独立的路，一条断了
    另一条还有用。
    """
    code, out, err = node_registry.run(client, profile_command(bin_dir_value))
    if code != 0:
        return f'写入失败：{err or out or "退出码 " + str(code)}'
    if bin_dir_value not in out:
        return f'写入后回读的内容里没有 {bin_dir_value}：{out.strip() or "空文件"}'
    context.log('system', f'节点 {label}：{PROFILE_PATH} 已指向 {bin_dir_value}')
    return True


def _ensure_environment(context, client, label, bin_dir_value):
    """把 ``bin_dir`` 追加进 ``/etc/environment`` 的 ``PATH=``，成功返回 True，失败返回原因。

    参数：`context` 表示任务上下文；`client` 表示已连接的客户端；`label` 表示节点标识；
        `bin_dir_value` 表示二进制目录。
    返回：成功返回 True；无需改动返回说明文本；失败返回原因文本。
    副作用：在目标机上改写 ``/etc/environment``。

    这是**唯一一处修改既有系统文件**的动作，所以每一步都留退路：读不到就跳过、没有
    ``PATH=`` 这一行就跳过（宁可不动，也不去猜一个默认值塞进去）、写完回读核对。
    跳过时写的是 ``warn`` 级别的事件，原因里带一句「非交互式 SSH 里仍要写全路径」，
    操作员据此知道可以手工补。
    """
    code, out, err = read_text(client, ENVIRONMENT_PATH)
    if code != 0:
        return _skip_environment(context, label, f'读不到（{err}）')

    updated, info = environment_content(out, bin_dir_value, add=True)
    if not info['matched']:
        return _skip_environment(context, label, f'没有 {ENVIRONMENT_KEY}= 这一行')
    if not info['changed']:
        context.log('system', f'节点 {label}：{ENVIRONMENT_PATH} 的 {ENVIRONMENT_KEY} 里已经有 {bin_dir_value}')
        return True

    code, out, err = node_registry.run(client, write_text_command(ENVIRONMENT_PATH, updated))
    if code != 0:
        return _skip_environment(context, label, f'写入失败（{err or out or "退出码 " + str(code)}）')

    # 回读一遍再确认：写成功不等于写对，配置管理工具正好也在改这个文件时，
    # 上面的 mv 会被它覆盖回去，而那时命令本身是成功的。
    if not _environment_has(client, bin_dir_value):
        return _skip_environment(context, label, '写入后回读核对不上')
    context.log(
        'system',
        f'节点 {label}：{ENVIRONMENT_PATH} 的 {ENVIRONMENT_KEY} 已改为 '
        f'"{info["after"]}"（原为 "{info["before"]}"），非交互式 SSH 也会带上它',
    )
    return True


def _environment_has(client, bin_dir_value):
    """判断 ``/etc/environment`` 的 ``PATH=`` 里现在是否含有 ``bin_dir``。

    参数：`client` 表示已连接的客户端；`bin_dir_value` 表示要核对的目录。
    返回：含有时返回 True，否则返回 False。
    副作用：在目标机上读一次文件。
    """
    code, out, _err = read_text(client, ENVIRONMENT_PATH)
    if code != 0:
        return False
    _updated, info = environment_content(out, bin_dir_value, add=True)
    return bool(info['matched']) and not info['changed']


def _skip_environment(context, label, reason):
    """统一的「没动 ``/etc/environment``」处理：写给操作员看的警告。

    参数：`context` 表示任务上下文；`label` 表示节点标识；`reason` 表示跳过的原因。
    返回：返回原因文本（供报告使用）。
    副作用：往任务日志与事件里写一条 warn。
    """
    message = (
        f'未修改 {ENVIRONMENT_PATH}（{reason}）。'
        f'这不影响集群本身：登录 shell 已经能从 {PROFILE_PATH} 拿到。'
        f'但 `ssh 节点 "kubectl ..."` 这类非交互式命令仍要写全路径。'
    )
    context.log('system', f'节点 {label}：{message}')
    context.event('node_path_partial', message, level='warn', detail={'node': label})
    return reason


def remove_node(context, node, bin_dir_value, credential=None, key_path=None, client_factory=None):
    """把 ``apply_node`` 在节点上留下的两处配置撤掉。

    参数：`context` 表示任务上下文；`node` 表示节点快照；`bin_dir_value` 表示当初加进去的
        目录；其余同 ``apply_node``。
    返回：返回 ``{'label', 'profile', 'environment'}`` 的报告字典。
    副作用：删除目标机上的 ``/etc/profile.d/kubeasz-path.sh``、改写 ``/etc/environment``。

    幂等：文件不在、``PATH`` 里本来就没有它，都算成功。
    ``bin_dir`` 里的命令**不删** —— 那批文件归 kubeasz 管，它的清理剧本里本来就把这一步
    注释掉了，删除是一行 rm，留给操作员自己决定。
    """
    label = str(getattr(node, 'ip_address', '') or '') or getattr(node, 'name', '节点')
    client = node_registry.open_session(
        node, credential, key_path=key_path, client_factory=client_factory,
    )
    try:
        report = {'label': label}
        code, out, err = node_registry.run(client, profile_remove_command())
        if code != 0:
            report['profile'] = f'删除失败：{err or out or "退出码 " + str(code)}'
        elif 'REMOVED' in out:
            context.log('system', f'节点 {label}：已删除 {PROFILE_PATH}')
            report['profile'] = True
        elif 'ABSENT' in out:
            report['profile'] = '本来就不在'
        else:
            # 文件不是平台写的那一份，不动它，只提示。
            report['profile'] = '文件内容不是平台写入的，已保留'
            context.log('system', f'节点 {label}：{PROFILE_PATH} 不是平台写入的，已保留未删除')

        report['environment'] = _remove_environment(context, client, label, bin_dir_value)
    finally:
        node_registry.close_session(client)
    return report


def _remove_environment(context, client, label, bin_dir_value):
    """从 ``/etc/environment`` 的 ``PATH=`` 里摘掉 ``bin_dir``。

    参数：`context` 表示任务上下文；`client` 表示已连接的客户端；`label` 表示节点标识；
        `bin_dir_value` 表示当初加进去的目录。
    返回：成功或无需改动返回 True；跳过时返回原因文本。
    副作用：在目标机上改写 ``/etc/environment``。

    读不到、没有 ``PATH=`` 都只记日志，不抛错 —— 销毁流程里的这类残留值得写一行警告，
    不值得让整个任务失败。
    """
    code, out, err = read_text(client, ENVIRONMENT_PATH)
    if code != 0:
        context.log('system', f'节点 {label}：读不到 {ENVIRONMENT_PATH}，跳过恢复（{err}）')
        return '读不到，已跳过'
    updated, info = environment_content(out, bin_dir_value, add=False)
    if not info['matched'] or not info['changed']:
        return True
    code, out, err = node_registry.run(client, write_text_command(ENVIRONMENT_PATH, updated))
    if code != 0:
        context.log(
            'system',
            f'注意：节点 {label} 的 {ENVIRONMENT_PATH} 恢复失败（{err or out or "退出码 " + str(code)}），'
            f'里面仍留着 {bin_dir_value}，不影响重新部署。',
        )
        return f'恢复失败：{err or out}'
    context.log('system', f'节点 {label}：{ENVIRONMENT_PATH} 的 {ENVIRONMENT_KEY} 已去掉 {bin_dir_value}')
    return True


def bin_dir_for(hosts_path):
    """从渲染后的 inventory 里读出本次部署的 ``bin_dir``。

    参数：`hosts_path` 表示 inventory 文件路径。
    返回：返回目录路径，读不到文件时返回 ``compiler.DEFAULT_BIN_DIR``。
    副作用：读一次文件。

    读失败不报错：这一步是给人用的便利配置，不值得为一句「文件不在」把部署拦下来 ——
    真的走到了那一步，缺文件这件事在别处已经暴露了。
    """
    try:
        text = open(str(hosts_path), encoding='utf-8').read()
    except OSError:
        return compiler.DEFAULT_BIN_DIR
    return compiler.bin_dir(text)
